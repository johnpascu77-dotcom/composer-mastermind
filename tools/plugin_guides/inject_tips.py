"""Adds hand-written tooltips to the constructor of a JUCE view class.

  python inject_tips.py <file.cpp> <ClassName> <tips.json>

tips.json maps a member variable name to its text; every `member.setTooltip (...)` line is written just before the
closing brace of `ClassName::ClassName(` (a labelled control can list its label too: use two keys with the same text).
A block already written by this script (marked) is replaced, so the command can be run again after editing the JSON.
"""
import json
import re
import sys

MARK_BEGIN = '    // [tooltips] generated by tools/plugin_guides/inject_tips.py from %s'
MARK_END = '    // [/tooltips]'


def cpp_string(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    path, cls, tips_path = sys.argv[1:4]
    raw = open(path, 'rb').read()
    bom = raw.startswith(b'\xef\xbb\xbf')
    src = raw.decode('utf-8-sig')
    nl = '\r\n' if '\r\n' in src else '\n'
    src = src.replace('\r\n', '\n')
    tips = json.load(open(tips_path, encoding='utf-8'))
    # drop an earlier generated block
    src = re.sub(r'\n    // \[tooltips\][^\n]*\n.*?\n    // \[/tooltips\]\n?', '\n', src, flags=re.S)
    m0 = re.search(r'\n(?:[\w:<>]+\s+)?' + re.escape(cls) + r'::' + re.escape(cls) + r'\s*\(', src)
    if not m0:
        sys.exit('constructor %s::%s not found in %s' % (cls, cls, path))
    i = src.index('{', m0.end())
    depth, j = 0, i
    while True:
        c = src[j]
        if c == '{':
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                break
        j += 1
    lines = [MARK_BEGIN % tips_path.replace('\\', '/').split('/')[-1]]
    for member, text in tips.items():
        lines.append('    %s.setTooltip(%s);' % (member, cpp_string(text)))
    lines.append(MARK_END)
    block = '\n' + '\n'.join(lines) + '\n'
    src = src[:j].rstrip('\n') + '\n' + block + src[j:]
    open(path, 'w', newline='', encoding='utf-8-sig' if bom else 'utf-8').write(src.replace('\n', nl))
    print('%s: %d tooltips in %s::%s' % (path.split('/')[-1], len(tips), cls, cls))


if __name__ == '__main__':
    main()
